# Recursive deletes of these are routine and safe: regenerated by a build.
EPHEMERAL_TARGETS = {
    ".next", "node_modules", "dist", "build", "out",
    ".turbo", ".cache", "coverage", ".vite", ".svelte-kit", "__pycache__",
}

# Never acceptable as a recursive-delete target, chained or not.
# The configured workspace_root is added at runtime (see forbidden_targets()).
FORBIDDEN_TARGETS = {"/", "~", "~/", ".", "..", "*", "/*", ".git"}


def forbidden_targets(workspace_root: Optional[str]) -> set:
    """Return FORBIDDEN_TARGETS plus the workspace root in its common spellings.

    :param workspace_root: the configured workspace root (absolute), or None.
    :return: set of target strings that may never be recursively deleted.
    """
    out = set(FORBIDDEN_TARGETS)
    if workspace_root:
        out.add(workspace_root.rstrip("/"))
        home = os.path.expanduser("~")
        if workspace_root.startswith(home + "/"):
            out.add("~" + workspace_root[len(home):].rstrip("/"))
    return out


def segments(command):
    """Split a command into pipeline/list segments on UNQUOTED separators only.

    Quote-awareness is not optional here: a naive split on `;` would cut inside
    `git commit -m "fix; rm -rf must stand alone"`, producing a phantom segment
    that starts with `rm -rf` and false-blocking an innocent commit message.
    """
    segs, cur, quote, i = [], [], None, 0
    while i < len(command):
        ch = command[i]
        if quote:
            cur.append(ch)
            if ch == quote and command[i - 1] != "\\":
                quote = None
            i += 1
            continue
        if ch in ('"', "'"):
            quote = ch
            cur.append(ch)
            i += 1
            continue
        if command.startswith("&&", i) or command.startswith("||", i):
            segs.append("".join(cur))
            cur = []
            i += 2
            continue
        if ch in (";", "|", "\n"):
            segs.append("".join(cur))
            cur = []
            i += 1
            continue
        cur.append(ch)
        i += 1
    segs.append("".join(cur))
    return [s.strip() for s in segs if s.strip()]


def tokens(segment):
    """Whitespace-split one segment.

    :param segment: one command segment.
    :return: list of words.
    """
    return segment.split()


def is_recursive_rm(seg_tokens):
    """True when this segment is an `rm` with a recursive flag."""
    if not seg_tokens or seg_tokens[0] != "rm":
        return False
    for tok in seg_tokens[1:]:
        if tok == "--recursive":
            return True
        if tok.startswith("-") and not tok.startswith("--") and "r" in tok.lower():
            return True
    return False


def rm_targets(seg_tokens):
    """Return the non-flag arguments of an rm segment.

    :param seg_tokens: words of the segment, starting with "rm".
    :return: the delete targets.
    """
    return [t for t in seg_tokens[1:] if not t.startswith("-")]


def basename(path):
    """Return the last path component, ignoring a trailing slash.

    :param path: a path string.
    :return: its basename.
    """
    return path.rstrip("/").rsplit("/", 1)[-1]


def all_targets_ephemeral(targets):
    """True when every delete target is a regenerable build artifact.

    :param targets: delete targets.
    :return: whether the chained delete is exempt from Rule A.
    """
    return bool(targets) and all(basename(t) in EPHEMERAL_TARGETS for t in targets)


def check_delete_shape(command, workspace_root=None):
    """Rule A. Returns a block reason, or None.

    :param command: the Bash command text.
    :param workspace_root: configured workspace root, added to the forbidden targets.
    :return: block reason or None.
    """
    never = forbidden_targets(workspace_root)
    segs = segments(command)
    for seg in segs:
        toks = tokens(seg)
        if not is_recursive_rm(toks):
            continue

        targets = rm_targets(toks)

        for t in targets:
            if t.rstrip("/") in never or t in never:
                return (
                    "Command-shape guard: refusing a recursive delete of {!r}.\n"
                    "This target is never deletable via this hook. If you truly mean it, "
                    "ask the user to run it themselves.".format(t)
                )

        if len(segs) == 1:
            continue  # standing alone — allowed
        if all_targets_ephemeral(targets):
            continue  # `rm -rf .next && pnpm build` and friends

        return (
            "Command-shape guard: a recursive delete may not be chained with other "
            "commands.\n"
            "  Command:  {}\n"
            "  Deleting: {}\n"
            "Why: when you combine listing and deleting in one call, the file list "
            "prints AFTER the delete has already run — you read the manifest too late "
            "to stop.\n"
            "Do this instead: (1) run the `ls`/`find` as its own call and READ the "
            "output; (2) then run the `rm -rf` alone, scoped to the exact path you "
            "confirmed. Build artifacts ({}) are exempt.".format(
                command.strip()[:200],
                ", ".join(targets) or "(no explicit target)",
                ", ".join(sorted(EPHEMERAL_TARGETS)),
            )
        )
    return None


# Rule B only speaks up for git verbs that change a repo or talk to its remote.
# Read-only verbs (status, log, diff, show, rev-parse, ...) on the wrong repo cost
# nothing but a confusing answer, so they stay silent.
GIT_WRITE_VERBS = {
    "add", "am", "apply", "checkout", "cherry-pick", "clean", "commit", "merge",
    "mv", "pull", "push", "rebase", "reset", "restore", "revert", "rm", "stash",
    "switch", "tag",
}

# git options that consume the following token as their value.
GIT_OPTS_WITH_VALUE = {"-C", "-c", "--git-dir", "--work-tree", "--namespace"}


def find_repo_root(path):
    """Walk up from `path` to the nearest directory holding `.git` (dir or file).

    :param path: absolute directory to start from.
    :return: the repo root, or None when `path` is not inside a git repo.
    """
    current = os.path.abspath(path)
    while True:
        if os.path.exists(os.path.join(current, ".git")):
            return current
        parent = os.path.dirname(current)
        if parent == current:
            return None
        current = parent


def git_verb_and_dir(toks, base_dir):
    """Split `git [opts] <verb> ...` into the verb and the directory git will run in.

    :param toks: tokens of one segment, starting with "git".
    :param base_dir: directory the segment runs in (cwd, or a preceding `cd`).
    :return: (verb or None, directory).
    """
    run_dir = base_dir
    i = 1
    while i < len(toks):
        tok = toks[i]
        if tok in GIT_OPTS_WITH_VALUE:
            if tok == "-C" and i + 1 < len(toks):
                run_dir = os.path.join(run_dir, os.path.expanduser(toks[i + 1]))
            i += 2
            continue
        if tok.startswith("-"):
            i += 1
            continue
        return tok, run_dir
    return None, run_dir


def check_git_scope(command, cwd=""):
    """Rule B. Name the repo a state-changing git command will hit.

    Claude Code strips a redundant leading `cd <cwd> &&` before the hook sees the
    command, so "is there a cd?" can't be the test (it fires on every git call).
    Instead: resolve where git will actually run (`-C`, a preceding `cd`, else the
    session cwd) and say which repo that is, for write/remote verbs only.

    :param command: the Bash command string.
    :param cwd: the session cwd from the PreToolUse payload.
    :return: a context note naming the target repo, or None.
    """
    run_dir = cwd or os.getcwd()
    for seg in segments(command):
        toks = tokens(seg)
        if not toks:
            continue
        if toks[0] == "cd" and len(toks) > 1:
            run_dir = os.path.join(run_dir, os.path.expanduser(toks[1]))
            continue
        if toks[0] != "git":
            continue
        verb, git_dir = git_verb_and_dir(toks, run_dir)
        if verb not in GIT_WRITE_VERBS:
            continue
        root = find_repo_root(git_dir) or "(not inside a git repo)"
        return (
            "Command-shape guard (note): `git {}` will run in repo {}. "
            "If that is not the repo you mean, stop and target it explicitly; "
            "nested repos make a wrong-repo {} easy.".format(verb, root, verb)
        )
    return None


# ---------------------------------------------------------------------------
# Rule C — sandbox-excluded commands must stand alone
# ---------------------------------------------------------------------------

# Used only when no settings file yields an excludedCommands list, so the rule
# never silently turns itself off.
DEFAULT_EXCLUDED_COMMANDS = ["git fetch *", "git push *", "git pull *"]

# Settings files whose sandbox.excludedCommands arrays Claude Code merges.
USER_SETTINGS_PATH = "~/.claude/settings.json"
PROJECT_SETTINGS_FILES = (".claude/settings.json", ".claude/settings.local.json")

# Shell grammar words that carry no command of their own.
STRUCTURAL_WORDS = {"do", "done", "then", "fi", "else", "{", "}", "(", ")"}

# Wrappers Claude Code strips before matching Bash rules (permissions docs, "Wrappers").
WRAPPER_RE = re.compile(
    r"^(timeout(\s+-\S+)*\s+\S+\s+|time\s+|nice(\s+-n\s*-?\d+|\s+-\d+)?\s+|nohup\s+"
    r"|stdbuf(\s+-\S+)*\s+|command\s+|builtin\s+|noglob\s+)"
)
ASSIGNMENT_PREFIX_RE = re.compile(r"""^[A-Za-z_][A-Za-z0-9_]*=("[^"]*"|'[^']*'|\S*)\s+""")
PURE_ASSIGNMENT_RE = re.compile(r"""^[A-Za-z_][A-Za-z0-9_]*=("[^"]*"|'[^']*'|\S*)$""")
LEADING_KEYWORD_RE = re.compile(r"^(do|then|else)\s+")

# Stands in for a masked substitution so its body can't split the outer line.
SUBSTITUTION_PLACEHOLDER = "__SUB__"
# Deepest nesting of $(...) inspected before giving up and treating a body as unsafe.
MAX_SUBSTITUTION_DEPTH = 4


def load_excluded_patterns(event):
    """Merge sandbox.excludedCommands from the user and project settings files.

    :param event: the PreToolUse payload (its `cwd` locates the project if
        CLAUDE_PROJECT_DIR is unset)
    :return: the merged pattern list, or DEFAULT_EXCLUDED_COMMANDS if none was found
    """
    paths = [os.path.expanduser(USER_SETTINGS_PATH)]
    project_dir = os.environ.get("CLAUDE_PROJECT_DIR") or (event or {}).get("cwd") or ""
    if project_dir:
        paths.extend(os.path.join(project_dir, rel) for rel in PROJECT_SETTINGS_FILES)
    patterns = []  # type: List[str]
    for path in paths:
        try:
            with open(path, encoding="utf-8") as fh:
                entries = ((json.load(fh).get("sandbox") or {}).get("excludedCommands")) or []
        except (OSError, ValueError, AttributeError):
            continue
        patterns.extend(e for e in entries if isinstance(e, str) and e not in patterns)
    return patterns or list(DEFAULT_EXCLUDED_COMMANDS)


def pattern_regex(pattern):
    """Compile a Bash-rule pattern the way Claude Code matches it.

    `*` matches any text; a single trailing ` *` (or `:*`) also matches the bare command.

    :param pattern: an excludedCommands entry such as "git push *"
    :return: a compiled, fully anchored regex
    """
    if pattern.endswith(":*"):
        pattern = pattern[:-2] + " *"
    if pattern.endswith(" *") and pattern.count("*") == 1:
        return re.compile(r"^" + re.escape(pattern[:-2]) + r"(\s.*)?$", re.S)
    return re.compile(r"^" + ".*".join(re.escape(p) for p in pattern.split("*")) + r"$", re.S)


def loose_pattern_regex(pattern):
    """Unanchored version of a pattern's literal prefix, for parse-unreliable lines.

    :param pattern: an excludedCommands entry
    :return: regex finding the prefix words anywhere at a word boundary
    """
    words = pattern.replace(":*", " *").split("*")[0].split()
    return re.compile(r"(^|[\s;&|(`])" + r"\s+".join(re.escape(w) for w in words) + r"(\s|$|[;&|)`])")


def _matching_close(text, start, open_ch, close_ch):
    """Index just past the bracket closing the one opened before `start` (quote-aware).

    :param text: source text
    :param start: index of the first character inside the bracket
    :param open_ch: opening bracket character
    :param close_ch: closing bracket character
    :return: index after the closing bracket, or len(text) if it never closes
    """
    depth, quote, j = 1, None, start
    while j < len(text) and depth:
        c = text[j]
        if quote:
            if c == quote and (quote == "'" or text[j - 1] != "\\"):
                quote = None
        elif c in ("'", '"'):
            quote = c
        elif c == open_ch:
            depth += 1
        elif c == close_ch:
            depth -= 1
        j += 1
    return j


def mask_substitutions(command):
    """Replace $(...), `...`, <(...) and >(...) with a placeholder.

    :param command: Bash command text
    :return: (masked text, list of $(...) bodies, list of backtick/process-substitution bodies)
    """
    out, bodies, raw_bodies = [], [], []
    in_single, in_double, i, n = False, False, 0, len(command)
    while i < n:
        ch = command[i]
        if ch == "\\" and not in_single and i + 1 < n:
            out.append(command[i:i + 2])
            i += 2
            continue
        if ch == "'" and not in_double:
            in_single = not in_single
        elif ch == '"' and not in_single:
            in_double = not in_double
        elif not in_single:
            if command.startswith("$((", i):
                end = _matching_close(command, i + 3, "(", ")")
                end = end + 1 if end < n and command[end] == ")" else end
                out.append("0")
                i = end
                continue
            if command.startswith("$(", i):
                end = _matching_close(command, i + 2, "(", ")")
                bodies.append(command[i + 2:end - 1])
                out.append(SUBSTITUTION_PLACEHOLDER)
                i = end
                continue
            if ch == "`":
                end = command.find("`", i + 1)
                end = n if end == -1 else end + 1
                raw_bodies.append(command[i + 1:end - 1])
                out.append(SUBSTITUTION_PLACEHOLDER)
                i = end
                continue
            if ch in "<>" and command.startswith("(", i + 1) and not in_double:
                end = _matching_close(command, i + 2, "(", ")")
                raw_bodies.append(command[i + 2:end - 1])
                out.append(SUBSTITUTION_PLACEHOLDER)
                i = end
                continue
        out.append(ch)
        i += 1
    return "".join(out), bodies, raw_bodies


def split_with_operators(command):
    """Quote-aware split into (operator_before, segment) pairs.

    Separators: && || |& | ; & and newline. A `&` inside a redirect (2>&1, &>file,
    >&2) is not a separator.

    :param command: Bash command text (substitutions should already be masked)
    :return: list of (operator or None, raw segment text)
    """
    pairs = []  # type: List[Tuple[Optional[str], str]]
    cur, quote, op, i, n = [], None, None, 0, len(command)
    while i < n:
        ch = command[i]
        if quote:
            cur.append(ch)
            if ch == quote and (quote == "'" or command[i - 1] != "\\"):
                quote = None
            i += 1
            continue
        if ch == "\\" and i + 1 < n:
            cur.append(command[i:i + 2])
            i += 2
            continue
        if ch in ('"', "'"):
            quote = ch
            cur.append(ch)
            i += 1
            continue
        sep = None
        for two in ("&&", "||", "|&"):
            if command.startswith(two, i):
                sep = two
                break
        if sep is None and ch in (";", "|", "\n"):
            sep = ch
        if sep is None and ch == "&":
            prev_ch = command[i - 1] if i > 0 else ""
            next_ch = command[i + 1] if i + 1 < n else ""
            if prev_ch not in ("<", ">") and next_ch != ">":
                sep = "&"
        if sep is None:
            cur.append(ch)
            i += 1
            continue
        pairs.append((op, "".join(cur)))
        cur, op = [], sep
        i += len(sep)
    pairs.append((op, "".join(cur)))
    return [(o, s.strip()) for o, s in pairs if s.strip()]


def normalize_segment(segment):
    """Strip grouping, leading control keywords, env assignments and wrappers.

    :param segment: one raw segment
    :return: the command text Claude Code would match rules against
    """
    s = segment.strip()
    changed = True
    while changed and s:
        before = s
        s = s.lstrip("({").rstrip(")}").strip()
        s = LEADING_KEYWORD_RE.sub("", s)
        if not PURE_ASSIGNMENT_RE.match(s):
            s = ASSIGNMENT_PREFIX_RE.sub("", s)
        s = WRAPPER_RE.sub("", s)
        changed = s != before
    return s


def has_file_redirect(masked):
    """True for an unquoted output redirect whose target is not /dev/null or an fd.

    :param masked: command text with substitutions already masked
    :return: whether output goes into a file
    """
    unquoted = re.sub(r"'[^']*'|\"(\\.|[^\"\\])*\"", " ", masked)
    for m in re.finditer(r"(&>>?|>>?\|?)\s*(&\d*-?|[^\s;&|()<>]*)", unquoted):
        target = m.group(2)
        if not target or target.startswith("&"):
            continue  # fd duplication such as 2>&1
        if target in ("/dev/null", "/dev/stdout", "/dev/stderr"):
            continue
        return True
    return False


def parse_is_unreliable(command):
    """True when a heredoc or an unbalanced quote could hide separators from the parser.

    :param command: Bash command text
    :return: whether the structured split can't be trusted
    """
    if "<<" in command:
        return True
    quote, i = None, 0
    while i < len(command):
        ch = command[i]
        if ch == "\\" and quote != "'":
            i += 2
            continue
        if quote:
            if ch == quote:
                quote = None
        elif ch in ("'", '"'):
            quote = ch
        i += 1
    return quote is not None


def find_excluded(command, regexes, depth=0):
    """Excluded-command matches in a line, including inside substitutions.

    :param command: Bash command text
    :param regexes: compiled excludedCommands patterns
    :param depth: current nesting depth
    :return: list of matching normalized segments
    """
    masked, bodies, raw_bodies = mask_substitutions(command)
    found = [s for _, s in ((o, normalize_segment(seg)) for o, seg in split_with_operators(masked))
             if s and any(r.match(s) for r in regexes)]
    if depth < MAX_SUBSTITUTION_DEPTH:
        for b in bodies + raw_bodies:
            found.extend(find_excluded(b, regexes, depth + 1))
    return found


def excluded_escape_problems(command, patterns):
    """Rule C analysis: which excluded command is present and what shares its line.

    :param command: the full Bash command text
    :param patterns: merged sandbox.excludedCommands entries
    :return: (excluded matches, problems); problems is empty only when the
             excluded command stands alone on its line
    """
    regexes = [pattern_regex(p) for p in patterns]
    excluded = find_excluded(command, regexes)
    unreliable = parse_is_unreliable(command)
    if not excluded and unreliable:
        loose = [loose_pattern_regex(p) for p in patterns]
        hit = next((m.group(0).strip(" ;&|()`") for r in loose for m in [r.search(command)] if m), None)
        if hit:
            return [hit], ["a heredoc or unbalanced quote, so the line can't be parsed reliably"]
    if not excluded:
        return [], []
    problems = []  # type: List[str]
    masked, bodies, raw_bodies = mask_substitutions(command)
    if unreliable:
        problems.append("a heredoc or unbalanced quote, so the line can't be parsed reliably")
    if raw_bodies:
        problems.append("backticks or process substitution <(...)")
    if bodies:
        problems.append("command substitution $({})".format(bodies[0].strip()[:50]))
    if has_file_redirect(masked):
        problems.append("an output redirect into a file")
    for _, seg in split_with_operators(masked):
        s = normalize_segment(seg)
        if s and s not in excluded and s not in STRUCTURAL_WORDS:
            problems.append("`{}`".format(s[:80]))
    return excluded, problems


def check_excluded_escape(command, patterns):
    """Rule C. Returns a block reason, or None.

    :param command: the full Bash command text
    :param patterns: merged sandbox.excludedCommands entries
    :return: block reason when an excluded command shares its line with anything
    """
    excluded, problems = excluded_escape_problems(command, patterns)
    if not problems:
        return None
    return (
        "Command-shape guard: `{}` matches sandbox.excludedCommands, but this line "
        "also contains: {}.\n"
        "Why: since Claude Code 2.1.277 every part of a line must match an exclusion, "
        "so anything else on it (even `cd`, `sleep`, `echo` or `| tail`) keeps the "
        "whole line sandboxed and `{}` fails on the network (git over SSH, gh to "
        "api.github.com).\n"
        "Do this instead: run `{}` ALONE in its own Bash call (cd first in a separate "
        "call, then confirm with `git rev-parse --show-toplevel`). For gh output you "
        "need to filter, run the bare gh call, or set dangerouslyDisableSandbox on the "
        "piped form so the user gets prompted.".format(
            excluded[0][:80], "; ".join(problems[:4]), excluded[0][:80], excluded[0][:80],
        )
    )


# ---------------------------------------------------------------------------
# Rule D — $TMPDIR differs between sandboxed and unsandboxed calls
# ---------------------------------------------------------------------------

TMPDIR_REF = re.compile(r"\$\{?TMPDIR\b")


def check_unsandboxed_tmpdir(command: str, scratch_dir: Optional[str] = None) -> Optional[str]:
    """Rule D. Block an unsandboxed command that references $TMPDIR.

    :param command: the Bash command string.
    :param scratch_dir: configured scratch dir to suggest, or None.
    :return: a block reason, or None when $TMPDIR is not referenced.
    """
    if not TMPDIR_REF.search(command):
        return None
    where = scratch_dir or "a scratch directory inside the project (e.g. ./tmp/, gitignored)"
    return (
        "Rule D: this call runs unsandboxed, where $TMPDIR is a DIFFERENT directory "
        "than in sandboxed calls — files won't be where the other side expects. "
        "Use {} for scratch instead (writable both ways).".format(where)
    )


def main():
    """Hook entry point: run Rules A-D against a Bash call.

    :return: None (prints a deny, a warning, or nothing).
    """
    event = read_event()
    if event is None or event.get("tool_name") != "Bash":
        return

    tool_input = event.get("tool_input") or {}
    command = tool_input.get("command", "") or ""
    if not command.strip():
        return

    config = load_config()  # optional: only sharpens Rules A and D
    workspace_root = str(config.workspace_root) if config and config.workspace_root else None
    scratch_dir = str(config.scratch_dir) if config and config.scratch_dir else None

    blocked = check_delete_shape(command, workspace_root)
    if blocked:
        pretool_deny(blocked)
        return

    if tool_input.get("dangerouslyDisableSandbox"):
        tmpdir = check_unsandboxed_tmpdir(command, scratch_dir)
        if tmpdir:
            pretool_deny(tmpdir)
            return
    else:
        escape = check_excluded_escape(command, load_excluded_patterns(event))
        if escape:
            pretool_deny(escape)
            return

    warning = check_git_scope(command, event.get("cwd") or "")
    if warning:
        pretool_context(warning)


if __name__ == "__main__":
    main()

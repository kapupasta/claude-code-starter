#!/usr/bin/env python3
"""This file owns the command-shape guard: blocking Bash commands whose *shape* makes mistakes invisible.

Four rules about how a Bash command is composed. It is deliberately NOT about
*where* a command points (that is guard-scope.py). Every failure below happened
entirely inside allowed roots, so scope guarding could never have caught it.

Rule A - a recursive delete must be its own Bash call.  [BLOCK]
  An agent ran `find <dir> | head; rm -rf <dir>` in one call. The listing that
  would have revealed unrelated content printed AFTER the delete had already run.
  Inspection and destruction in one call means you always read the manifest too
  late. Forcing the delete to stand alone guarantees any listing happened in a
  PRIOR call whose output was actually read. Build artifacts (.next,
  node_modules, ...) are exempt: `rm -rf .next && pnpm build` is a safe idiom.

Rule B - name the repo a state-changing `git` will hit.  [NOTE]
  A workspace root that is itself a git repo holding nested project repos, plus
  a shell cwd that persists (and sometimes silently resets) across tool calls,
  makes a wrong-repo commit or push easy. For write/remote verbs (commit, push,
  pull, add, reset, checkout, ...) the hook resolves where git will actually run
  (`-C`, a preceding `cd`, else the session cwd) and adds one line to Claude's
  context naming that repo. Read-only verbs stay silent. (Testing for a `cd`
  doesn't work: Claude Code strips a redundant leading `cd <cwd> &&`.)

Rule C - a sandbox-excluded command must stand alone.  [BLOCK]
  Since Claude Code 2.1.277, EVERY part of a Bash line must match
  `sandbox.excludedCommands` for the line to run unsandboxed. Any sibling at all
  (even `cd`, `sleep`, `echo` or a pipe into `tail`) keeps the whole line
  sandboxed, and the excluded command (git over SSH, gh to api.github.com) fails
  on the network with an error that reads like an auth fault. Older builds had
  the opposite, worse behaviour: one matching part ran the WHOLE line
  unsandboxed with no prompt, so a sibling could read a credential-denied file.
  Either way the excluded command must be ALONE on its line, so this rule blocks
  every sibling, substitution and redirect next to one. A call flagged
  dangerouslyDisableSandbox is skipped: its ask rule already puts a human in
  front of the whole line.

Rule D - an unsandboxed command must not use $TMPDIR.  [BLOCK]
  Outside the sandbox $TMPDIR is the real /var/folders/... dir; inside it is a
  per-sandbox dir. A file written by one side is missing on the other, so the
  retry "can't find" what the sandboxed call just made. Scratch both sides need
  goes in scratch_dir from starter-config.json (inside the workspace, writable
  either way).

Reads a PreToolUse payload on stdin. Prints a hookSpecificOutput deny for a
block, additionalContext for a warning, and nothing otherwise (no opinion, so
the normal permission flow runs). Reads sandbox.excludedCommands from the user
and project settings files; works without starter-config.json.
"""

